G09B_LINES = [(1387, 1478), (1984, 2543)]          # ORIG 09 §7 and §10-§12


def _first_line(sel):
    if sel.startswith('L:'):
        return int(sel[2:].split('-')[0])
    return None


def split09(rows, fname):
    out = []
    for sel, act, own, sec, note in rows:
        if own == 'G09':
            if fname.startswith('08'):
                own = 'G09b'
            else:
                n = sel[2:].split('.')[0] if sel[:2] in ('S:', 'I:') else None
                ln = _first_line(sel)
                b = (n in {'7', '10', '11', '12'}) or (ln is not None and any(a <= ln <= z for a, z in G09B_LINES))
                own = 'G09b' if b else 'G09a'
        out.append((sel, act, own, sec, note))
    return out


