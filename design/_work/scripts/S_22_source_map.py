def main():
    with open(sys.argv[1], newline="", encoding="utf-8") as fh:
        manifest = {r["path"] for r in csv.DictReader(fh)}
    missing = [p for p, _ in ROWS if p not in manifest]
    if missing:
        sys.stderr.write("missing from manifest: %s\n" % ", ".join(missing))
        sys.exit(1)
    seen = set()
    out = ["| File | Role in this document |", "|---|---|"]
    for p, role in ROWS:
        if p in seen:
            continue
        seen.add(p)
        out.append("| `%s` | %s |" % (p, role))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
