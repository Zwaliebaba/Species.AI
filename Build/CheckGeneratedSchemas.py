"""CheckGeneratedSchemas.py: the drift check of the schema code generator (ADR-062, owner decision O28, AGENTS.md §2).

  python Build/CheckGeneratedSchemas.py [--generated <folder>]

Builds the generator through the solution (/t:Tools\\SpeciesSchemaGen, Debug|x64), runs it into a temporary tree and
compares that tree with the committed headers. A difference, a header the generator writes that is not committed, and
a committed generated header that it no longer writes each fail the check. A committed header is generated when its
first line starts with GENERATED_MARK. Line endings are git's choice, not the generator's, so CR LF and LF compare
equal. The check writes nothing into the checkout. --generated compares a tree the generator wrote elsewhere, and
skips the build. Before the tree it runs its fixture: a changed copy of a generated header must be reported.
"""
import argparse
import difflib
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import SolutionModel  # noqa: E402  (the path above makes the sibling module importable)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATOR = 'SpeciesSchemaGen'
GENERATOR_TARGET = 'Tools\\SpeciesSchemaGen'
GENERATOR_EXE = os.path.join('x64', 'Debug', 'SpeciesSchemaGen.exe')
SCHEMA_FOLDER = os.path.join('GameData', 'Schemas')
GENERATED_MARK = '// Generated by SpeciesSchemaGen'


def normalized(text):
  return text.replace('\r\n', '\n')


def read(path):
  with open(path, encoding='utf-8', newline='') as fh:
    return fh.read()


def committed_headers(root):
  """{relative path: text} of every committed header that the generator wrote, in the solution's project folders."""
  headers = {}
  _, projects = SolutionModel.load(root)
  for project in projects:
    folder = os.path.join(root, project.directory)
    for name in sorted(os.listdir(folder)):
      path = os.path.join(folder, name)
      if name.endswith('.h') and os.path.isfile(path):
        text = read(path)
        if text.startswith(GENERATED_MARK):
          headers[f'{project.directory}/{name}'.replace('\\', '/')] = text
  return headers


def generated_headers(folder):
  headers = {}
  for directory, _, names in os.walk(folder):
    for name in sorted(names):
      if name.endswith('.h'):
        path = os.path.join(directory, name)
        headers[os.path.relpath(path, folder).replace('\\', '/')] = read(path)
  return headers


def compare(committed, generated):
  """The findings of comparing the committed headers with a fresh tree."""
  findings = []
  for path in sorted(set(committed) | set(generated)):
    if path not in generated:
      findings.append(f'{path}: committed as generated, but the generator no longer writes it')
    elif path not in committed:
      findings.append(f'{path}: written by the generator, but not committed (run {GENERATOR} and commit its output)')
    elif normalized(committed[path]) != normalized(generated[path]):
      diff = difflib.unified_diff(normalized(committed[path]).splitlines(), normalized(generated[path]).splitlines(),
                                  'committed', 'generated', lineterm='', n=1)
      lines = list(diff)[:12]
      findings.append(f'{path}: differs from what the generator writes now\n  ' + '\n  '.join(lines))
  return findings


def run_fixture(committed):
  if not committed:
    return []
  path, text = next(iter(sorted(committed.items())))
  changed = {path: text + '// a hand edit\n'}
  if not compare({path: text}, changed):
    return [f'the fixture: a changed copy of {path} was not reported']
  return []


def build_and_generate(output):
  solutions = SolutionModel.find_solutions(ROOT)
  if len(solutions) != 1:
    return f'expected one solution at the root, found {len(solutions)}'
  command = ['msbuild', solutions[0], f'/t:{GENERATOR_TARGET}', '/p:Configuration=Debug', '/p:Platform=x64', '/m', '/nologo',
             '/v:minimal']
  if subprocess.run(command, cwd=ROOT).returncode != 0:
    return f'the generator did not build: {" ".join(command)}'
  run = subprocess.run([os.path.join(ROOT, GENERATOR_EXE), '--root', ROOT, '--out', output], cwd=ROOT)
  if run.returncode != 0:
    return f'the generator failed with exit code {run.returncode}'
  return None


def main():
  parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  parser.add_argument('--generated', help='a tree the generator already wrote; the build is skipped')
  args = parser.parse_args()

  committed = committed_headers(ROOT)
  schemas = [n for n in os.listdir(os.path.join(ROOT, SCHEMA_FOLDER)) if n.endswith('.schema.json')] \
    if os.path.isdir(os.path.join(ROOT, SCHEMA_FOLDER)) else []
  failures = run_fixture(committed)
  for failure in failures:
    print(f'CheckGeneratedSchemas: {failure}')
  if not schemas and not committed:
    print('CheckGeneratedSchemas: no schema and no generated header yet')
    return 1 if failures else 0

  with tempfile.TemporaryDirectory(prefix='CheckGeneratedSchemas.') as scratch:
    if args.generated:
      generated = generated_headers(args.generated)
    else:
      error = build_and_generate(scratch)
      if error:
        print(f'CheckGeneratedSchemas: {error}')
        return 1
      generated = generated_headers(scratch)
  findings = compare(committed, generated)
  for finding in findings:
    print(f'CheckGeneratedSchemas: {finding}')
  print(f'CheckGeneratedSchemas: {len(schemas)} schemas, {len(committed)} committed generated headers, {len(findings)} findings')
  return 1 if findings or failures else 0


if __name__ == '__main__':
  sys.exit(main())
